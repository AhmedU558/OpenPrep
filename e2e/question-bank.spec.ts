import { expect, test } from '@playwright/test';
import { choices, register, testDb } from './helpers';

test('authored bank: subject/topic filters, practice, distractors, references and disclosure', async ({ page }) => {
  await register(page);
  const db = testDb();
  const q = await db.question.findUniqueOrThrow({ where: { code: 'op26-0001' }, include: { options: { orderBy: { position: 'asc' } } } });
  await db.$disconnect();
  await page.goto('/questions');
  await page.getByRole('group', { name: 'Subject', exact: true }).getByText('Anatomy', { exact: true }).click();
  await page.getByRole('group', { name: 'Topic', exact: true }).getByText('Anatomy / Axillary nerve', { exact: true }).click();
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  await expect(page.getByText('1 question match.', { exact: false })).toBeVisible();
  await expect(page.getByText('op26-0001')).toBeVisible();
  await expect(page.getByText('AI-authored · medically unreviewed')).toBeVisible();
  await page.getByRole('button', { name: 'Practice', exact: true }).click();
  await expect(choices(page).first()).toBeEnabled();
  await expect(page.locator('#expl-h')).toHaveCount(0);
  await page.getByRole('radio').filter({hasText: q.options.find(o => o.isCorrect)!.text}).click();
  await page.getByRole('button', { name: 'Submit answer', exact: true }).click();
  await expect(page.locator('#expl-h')).toHaveText('Correct');
  await expect(page.getByRole('heading', { name: 'Why each choice' })).toBeVisible();
  for (const option of q.options) await expect(page.getByText(option.explanationMd!, {exact:true})).toBeVisible();
  await expect(page.getByRole('heading', {name:'References',exact:true})).toBeVisible();
  await expect(page.getByText(/Source: OpenPrep original; AI-authored; medically unreviewed/)).toBeVisible();
  await page.locator('.prose-q').last().selectText();
  await page.getByRole('button', { name: '+ Notebook from selection' }).click();
  await expect(page.getByText(/Added to your notebook/)).toBeVisible();
  await page.goto('/create');
  await page.getByLabel('Topic', {exact:true}).selectOption(q.topicId!);
  await page.getByLabel('Questions per block').fill('1');
  await page.getByText('All questions', {exact:false}).first().click();
  await page.getByRole('button', {name:'Generate test'}).click();
  await expect(choices(page).first()).toBeEnabled();
  await expect(page.getByText('ID op26-0001', {exact:true})).toBeVisible();
});

test('expansion: difficulty-four topic is usable with scoring, rationale, notes and marks',async({page})=>{
  await register(page);
  const db=testDb();
  const q=await db.question.findUniqueOrThrow({where:{code:'op26x-0715'},include:{options:true}});
  await db.$disconnect();
  await page.goto('/questions?difficulty=4');
  await page.getByRole('group',{name:'Topic',exact:true}).getByText('Biostatistics / Noninferiority interpretation',{exact:true}).click();
  await page.getByRole('button',{name:'Apply',exact:true}).click();
  await expect(page.getByText('1 question match.',{exact:false})).toBeVisible();
  await expect(page.getByText('Difficulty 4/5',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Practice',exact:true}).click();
  await expect(choices(page).first()).toBeEnabled();
  await page.getByRole('radio').filter({hasText:q.options.find(o=>o.isCorrect)!.text}).click();
  await page.getByRole('button',{name:'Submit answer',exact:true}).click();
  await expect(page.locator('#expl-h')).toHaveText('Correct');
  await expect(page.getByRole('heading',{name:'Why each choice'})).toBeVisible();
  await page.getByLabel('Mark',{exact:true}).check();
  await page.getByLabel('My notes').fill('Selection on a common effect can distort association.');
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await expect(page.getByText('Note saved.',{exact:true})).toBeVisible();
  await expect(page.getByText(/Source: OpenPrep original; AI-authored; medically unreviewed/)).toBeVisible();
});
