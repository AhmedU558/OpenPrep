// Offline evidence only: reads tracked source, reachable Git history and installed package notices; never loads .env or connects to a database.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import assert from 'node:assert/strict';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
const sha = (text) => createHash('sha256').update(text).digest('hex');
const json = (file) => JSON.parse(readFileSync(file, 'utf8'));
const out = 'docs/audit';
mkdirSync(out, { recursive: true });
const lock = json('package-lock.json');
const manifest = json('package.json');
const permissive = new Set(['MIT', 'MIT-0', 'ISC', 'BSD-2-Clause', 'BSD-3-Clause', '0BSD', 'Apache-2.0', 'BlueOak-1.0.0', 'CC0-1.0', 'Unlicense']);
const assess = (license) => {
  if (permissive.has(license)) return 'No obvious AGPL conflict; retain upstream notices and applicable patent/attribution terms.';
  if (license === '(MPL-2.0 OR Apache-2.0)') return 'Apache-2.0 alternative available; preserve dual-license notice.';
  if (/LGPL|MPL/.test(license)) return 'NEEDS REVIEW: file/library copyleft; retain source, notices and replacement/relinking rights as applicable to the shipped artifact.';
  if (/EPL/.test(license)) return 'NEEDS REVIEW: inspect secondary-license grant and separation; no AGPL compatibility conclusion.';
  if (license === 'CC-BY-4.0') return 'NEEDS REVIEW: data attribution, license link and modification notices; not a software license conclusion.';
  return 'NEEDS REVIEW: missing or compound license requires upstream text review.';
};
assert.match(assess('UNKNOWN'), /NEEDS REVIEW/);
assert.match(assess('EPL-2.0'), /NEEDS REVIEW/);
assert.doesNotMatch(assess('MIT'), /NEEDS REVIEW/);

const packages = Object.entries(lock.packages).filter(([path]) => path).map(([path, p]) => {
  const installed = existsSync(`${path}/package.json`) ? json(`${path}/package.json`) : null;
  const name = p.name ?? path.split('node_modules/').at(-1);
  const notices = installed ? readdirSync(path).filter((f) => /^(licen[sc]e|copying|notice)(\.|$|-)/i.test(f)).filter((f) => !f.includes('/')) : [];
  const license = p.license ?? installed?.license ?? 'UNKNOWN';
  return { name, version: p.version, path, direct: name in (manifest.dependencies ?? {}) || name in (manifest.devDependencies ?? {}), development: !!p.dev, optional: !!p.optional,
    license, lockLicense: p.license ?? null, installedLicense: installed?.license ?? null,
    source: p.resolved ?? null, integrity: p.integrity ?? null, upstream: installed?.repository ?? null,
    assessment: assess(typeof license === 'string' ? license : 'UNKNOWN'),
    requiredNotices: 'Retain upstream copyright, license and NOTICE files; see captured files and license-specific obligations.',
    redistribution: 'Review the actual source/binary/container bundle; package metadata alone is not compliance evidence.',
    unresolved: !installed ? 'Not installed on this platform; license text not captured.' : !notices.length ? 'No top-level license text found; inspect tarball or upstream.' : null,
    notices: notices.map((f) => ({ path: `${path}/${f}`, sha256: sha(readFileSync(`${path}/${f}`)) })) };
});
writeFileSync(`${out}/dependency-inventory.json`, JSON.stringify({ lockSha256: sha(readFileSync('package-lock.json')), scope: 'Every non-root lockfile package path, including optional platforms and dev dependencies; installed top-level notice evidence only.', packages }, null, 2) + '\n');
const esc = (s) => String(s ?? '').replaceAll('|', '\\|').replaceAll('\n', ' ');
writeFileSync(`${out}/dependency-inventory.md`, '# Dependency inventory\n\nGenerated by `node scripts/audit-open-source.mjs`. Each row is a lockfile installation path. This is a metadata assessment, not legal clearance. Full sources, integrity, license text hashes and evidence gaps are in [JSON](dependency-inventory.json).\n\n| Package | Version | Scope | License | Assessment | Notice evidence / unresolved |\n|---|---|---|---|---|---|\n' + packages.map((p) => `| ${esc(p.name)} | ${esc(p.version)} | ${p.development ? 'dev' : 'runtime'}${p.optional ? ', optional' : ''} | ${esc(p.license)} | ${esc(p.assessment)} | ${esc(p.unresolved ?? p.notices.map((n) => n.path).join(', '))} |`).join('\n') + '\n');
let notices = '# Captured third-party notices\n\nInstalled package top-level license/NOTICE files, verbatim. Platform-specific absent packages and nested bundled code require separate review. See dependency-inventory.json for file hashes and package source URLs.\n';
for (const p of packages) for (const n of p.notices) notices += `\n## ${p.name}@${p.version} — ${n.path}\n\n~~~~text\n${readFileSync(n.path, 'utf8')}\n~~~~\n`;
writeFileSync(`${out}/THIRD_PARTY_LICENSE_TEXTS.md`, notices);

const files = git('ls-files', '--cached', '--others', '--exclude-standard', '-z').split('\0').filter(Boolean);
const content = [];
for (const file of files.filter((f) => /^content\/bank\/(expansion\/)?generated\/.*\.json$/.test(f))) {
  for (const q of json(file)) content.push({ file, code: q.code, source: q.source, license: q.license, attribution: q.attribution, image: q.image ?? null, references: q.references?.map((r) => r.url).filter(Boolean), sha256: sha(JSON.stringify(q)), rights: 'Owner confirmed recorded redistribution rights on 2026-10-30; supporting evidence not supplied to this audit.', medicalReview: 'Unreviewed' });
}
assert(content.length > 0);
assert.equal(new Set(content.map((q) => q.code)).size, content.length);
writeFileSync(`${out}/content-provenance.json`, JSON.stringify({ scope: 'Tracked generated bank JSON only; seed and legacy content separately assessed in CONTENT_LICENSING_POLICY.md. No learner database access.', content }, null, 2) + '\n');

// Never emit matched text, blob contents, or credentials. Paths, commits and pattern labels only.
const patterns = [
  ['private-key', /-----BEGIN (?:RSA |EC |OPENSSH |DSA )?PRIVATE KEY-----/],
  ['github-token', /\b(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{50,})\b/],
  ['cloud-access-key', /\b(?:AKIA|ASIA)[A-Z0-9]{16}\b/],
  ['provider-key', /\bsk-(?:proj-|ant-)?[A-Za-z0-9_-]{24,}\b/],
  ['credential-url', /(?:postgres(?:ql)?|mysql|mongodb(?:\+srv)?):\/\/[^\s:'"/]+:[^\s@'"/]+@(?!localhost\b|127\.0\.0\.1\b|db\b)/i],
  ['literal-secret', /(?:BETTER_AUTH_SECRET|AI_API_KEY|SMTP_PASS|SEED_ADMIN_PASSWORD|JWT_SECRET)\s*[:=]\s*["']?[A-Za-z0-9_+\/-]{24,}/],
];
assert(patterns.find(([name]) => name === 'github-token')[1].test('ghp_' + 'x'.repeat(36)));
assert(!patterns.find(([name]) => name === 'credential-url')[1].test('postgresql://demo:local@localhost:5432/demo'));
const hits = [];
const seen = new Map();
const commits = git('rev-list', '--all').trim().split('\n').filter(Boolean);
for (const commit of commits) {
  for (const entry of git('ls-tree', '-r', '-z', commit).split('\0').filter(Boolean)) {
    const [meta, path] = entry.split('\t');
    const [, kind, oid] = meta.split(' ');
    if (kind !== 'blob') continue;
    if (!seen.has(oid)) {
      const body = git('cat-file', 'blob', oid);
      seen.set(oid, patterns.filter(([, regex]) => regex.test(body)).map(([name]) => name));
    }
    for (const pattern of seen.get(oid)) hits.push({ commit, path, pattern });
  }
}
const currentHits = [];
for (const file of files) {
  const body = readFileSync(file, 'utf8');
  for (const [pattern, regex] of patterns) if (regex.test(body)) currentHits.push({ path: file, pattern });
}
writeFileSync(`${out}/secret-scan.json`, JSON.stringify({ scope: 'All blobs reachable from local Git refs plus current tracked and non-ignored untracked files. Does not cover remote-only/unreachable objects, GitHub artifacts or ignored files. Heuristic scan; no clean-secret guarantee.', patterns: patterns.map(([name]) => name), commits: commits.length, uniqueBlobs: seen.size, sourceFiles: files.length, historyFindings: hits, currentFindings: currentHits }, null, 2) + '\n');
console.log(JSON.stringify({ dependencies: packages.length, licenseCounts: packages.reduce((a, p) => ({ ...a, [p.license]: (a[p.license] ?? 0) + 1 }), {}), absent: packages.filter((p) => !p.installedLicense).length, content: content.length, contentImages: content.filter((p) => p.image).length, commits: commits.length, uniqueBlobs: seen.size, historyFindings: hits, currentFindings: currentHits }, null, 2));
